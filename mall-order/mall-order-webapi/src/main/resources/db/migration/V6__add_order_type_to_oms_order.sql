-- ============================================================
-- V6: oms_order 增加 order_type 列（订单类型，区分秒杀/普通）
-- 背景: 秒杀订单与普通订单共用 oms_order 表，此前无类型标识，
--       导致 order 层无法区分（支付/取消/关单语义不同）——
--       markSeckillPurchased/clearSeckillOrdered 只能对所有订单
--       无条件执行（潜在 bug：普通订单误写秒杀购买标记）。
--       TODO #14 第2层前置 / #3 场次 / #11 超时关单 均依赖此标识。
-- 设计: 0=普通订单（默认），1=秒杀订单
--       历史数据默认 0（普通），演示数据无秒杀残留影响。
-- ============================================================
ALTER TABLE `oms_order`
    ADD COLUMN `order_type` int DEFAULT 0 COMMENT '订单类型，0=普通订单，1=秒杀订单' AFTER `payment_type`;
